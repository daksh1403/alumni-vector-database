import {existsSync,readFileSync,writeFileSync,mkdirSync,rmSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
if(!existsSync('frontend/index.html'))throw new Error('The backend-only repository does not include frontend assets. Supply the local frontend/ deployment directory first.');
mkdirSync('dist',{recursive:true});
const base=JSON.parse(readFileSync('wrangler.jsonc','utf8'));
delete base.$schema;
const config={...base,main:'../src/worker.js',assets:{directory:'../frontend',binding:'ASSETS',run_worker_first:true}};
writeFileSync('dist/wrangler.site.json',JSON.stringify(config,null,2));
const result=spawnSync('wrangler',['deploy','--config','dist/wrangler.site.json',...process.argv.slice(2)],{stdio:'inherit'});
rmSync('dist/wrangler.site.json',{force:true});
if(result.error)console.error(result.error.message);
process.exit(result.status ?? 1);
